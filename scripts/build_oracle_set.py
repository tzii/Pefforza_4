"""Generate the exact-oracle evaluation set (``pefforza/agent/data/oracle_positions.json``).

Every stored position carries the exact score of all seven columns, as
computed by Pascal Pons' native solver (see ``scripts/native_solver.py``).
Two populations, both seeded and reproducible:

* ``line`` - games where the evaluated side plays perfectly (the bundled
  opening book's move where it has one, the solver's best move otherwise,
  center-first on ties) and the opponent plays the best move or a uniformly
  random one with equal probability. Every position with the perfect side
  to move is kept, for both colors.
* ``random`` - games where both sides play the best move or a random one
  with equal probability; every third position is kept.

Usage::

    python scripts/build_oracle_set.py --solver path/to/c4solver
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from native_solver import INVALID, NativeSolver, moves_to_text  # noqa: E402

from pefforza.agent.oracle import DEFAULT_ORACLE_PATH  # noqa: E402
from pefforza.agent.search.bitboard import MOVE_ORDER, BitPosition  # noqa: E402
from pefforza.agent.search.book import DEFAULT_BOOK_PATH, OpeningBook  # noqa: E402


def best_move(scores: list[int]) -> int:
    top = max(s for s in scores if s != INVALID)
    return next(c for c in MOVE_ORDER if scores[c] == top)


def noisy_move(scores: list[int], rng: random.Random) -> int:
    if rng.random() < 0.5:
        return best_move(scores)
    return rng.choice([c for c in range(7) if scores[c] != INVALID])


def play(
    solver: NativeSolver,
    rng: random.Random,
    *,
    perfect_side: int | None,
    book: OpeningBook | None,
    keep_every: int,
):
    """Yield ``(moves, scores)`` for kept positions of one game."""
    moves: list[int] = []
    pos = BitPosition.empty()
    while not pos.is_full:
        scores = solver.analyze(moves)
        perfect = perfect_side is not None and pos.moves % 2 == perfect_side
        if perfect_side is None:
            if pos.moves % keep_every == 0:
                yield tuple(moves), scores
            col = noisy_move(scores, rng)
        elif perfect:
            yield tuple(moves), scores
            entry = book.lookup(pos) if book is not None else None
            col = entry.move if entry is not None else best_move(scores)
        else:
            col = noisy_move(scores, rng)
        pos = pos.played(col)
        moves.append(col)
        if pos.previous_player_won:
            return


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--solver", required=True, help="Path to Pons' c4solver binary.")
    p.add_argument("--line-games", type=int, default=40, help="Games per color.")
    p.add_argument("--random-games", type=int, default=30)
    p.add_argument("--seed", type=int, default=2026)
    p.add_argument("--book", type=Path, default=DEFAULT_BOOK_PATH)
    p.add_argument("--out", type=Path, default=DEFAULT_ORACLE_PATH)
    args = p.parse_args(argv)

    rng = random.Random(args.seed)
    book = OpeningBook.load(args.book) if args.book.exists() else None
    seen: set[str] = set()
    positions: list[dict] = []

    def keep(moves: tuple[int, ...], scores: list[int], source: str) -> None:
        text = moves_to_text(moves)
        if text in seen:
            return
        seen.add(text)
        positions.append(
            {
                "moves": text,
                "scores": [None if s == INVALID else s for s in scores],
                "source": source,
            }
        )

    with NativeSolver(args.solver) as solver:
        for side in (0, 1):
            for _ in range(args.line_games):
                for moves, scores in play(solver, rng, perfect_side=side, book=book, keep_every=1):
                    keep(moves, scores, "line")
        for _ in range(args.random_games):
            for moves, scores in play(solver, rng, perfect_side=None, book=None, keep_every=3):
                keep(moves, scores, "random")

    positions.sort(key=lambda item: (len(item["moves"]), item["moves"]))
    payload = {
        "description": (
            "Exact scores of every column (null = full) for positions with the "
            "side to move; columns are 1-based in 'moves'. Generated by "
            "scripts/build_oracle_set.py with Pascal Pons' solver."
        ),
        "seed": args.seed,
        "positions": positions,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    # One position per line keeps regenerated sets reviewable as diffs.
    head = json.dumps({k: v for k, v in payload.items() if k != "positions"})[:-1]
    body = ",\n".join(json.dumps(item, separators=(",", ":")) for item in positions)
    args.out.write_text(f'{head}, "positions": [\n{body}\n]}}\n', encoding="utf-8")
    lines = sum(1 for item in positions if item["source"] == "line")
    print(f"wrote {len(positions)} positions ({lines} line) to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
